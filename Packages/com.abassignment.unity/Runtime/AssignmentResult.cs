namespace AB.Assignment {
    /// <summary>
    /// Immutable assignment for this session (<see cref="ABAssignment.Current"/>). It does not change during the session.
    /// </summary>
    public sealed class AssignmentResult {
        internal const string SourceRemoteThisSession = "remote_this_session";
        internal const string SourceCachedRemote = "cached_remote";
        internal const string SourceUnassignedWaiting = "unassigned_waiting";
        internal const string SourceUnassignedError = "unassigned_error";

        /// <summary>Assigned group for <see cref="ExperimentId"/>. The kill switch does not change it.</summary>
        public Group Group { get; }

        /// <summary>metica | baseline | unassigned. Follows <see cref="Group"/>; used for placement tags and events.</summary>
        public string Label { get; }

        /// <summary>Whether the game routes ads to Metica this session: Group == Metica and Enabled. The debug override only applies when Enabled; the kill switch wins.</summary>
        public bool RunMetica { get; }

        /// <summary>The config "enabled" value in effect this session. False when unassigned.</summary>
        public bool Enabled { get; }

        /// <summary>The experiment in effect this session. Empty when unassigned.</summary>
        public string ExperimentId { get; }

        /// <summary>metica_percentage of the config in effect, in basis points (0..10000). 0 when unassigned.</summary>
        public int MeticaPercentageBasisPoints { get; }

        /// <summary>0..9999. -1 when unassigned.</summary>
        public int Bucket { get; }

        /// <summary>Generated by the library on first run, persisted, never changes. Empty only if it could not be loaded or created.</summary>
        public string UserId { get; }

        /// <summary>New value per cold start.</summary>
        public string SessionId { get; }

        /// <summary>
        /// Which config decided the group: "remote_this_session" (a Firebase value received earlier in this session),
        /// "cached_remote" (received in an earlier session), "unassigned_waiting" (no Firebase config yet when the
        /// group was needed) or "unassigned_error" (deciding failed).
        /// </summary>
        public string ConfigSource { get; }

        /// <summary>True in the first session of this device under <see cref="ExperimentId"/>. For QA only.</summary>
        public bool IsNewAssignment { get; }

        /// <summary>Why the device is unassigned; never empty when unassigned. Null when assigned.</summary>
        internal string Error { get; }

        internal AssignmentResult(Group group, bool runMetica, bool enabled, string experimentId,
            int meticaPercentageBasisPoints, int bucket, string userId, string sessionId, string configSource,
            bool isNewAssignment, string error) {
            Group = group;
            Label = Labels.For(group);
            RunMetica = runMetica;
            Enabled = enabled;
            ExperimentId = experimentId;
            MeticaPercentageBasisPoints = meticaPercentageBasisPoints;
            Bucket = bucket;
            UserId = userId;
            SessionId = sessionId;
            ConfigSource = configSource;
            IsNewAssignment = isNewAssignment;
            Error = error;
        }

        /// <summary>An unassigned result always carries a source and a non-empty error, so analytics can split it.</summary>
        internal static AssignmentResult CreateUnassigned(string userId, string sessionId, string source, string error) {
            if (string.IsNullOrEmpty(error)) {
                error = "unknown error";
            }
            return new AssignmentResult(Group.Unassigned, false, false, "", 0, -1, userId, sessionId, source, false, error);
        }
    }
}
